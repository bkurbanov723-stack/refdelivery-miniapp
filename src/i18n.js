export const LangContext = createContext({ lang: "uz", setLang: () => {} });

export function useLang() {
  return useContext(LangContext);
}

export function useT() {
  const { lang } = useContext(LangContext);
  return (key, vars) => {
    let s = DICT[lang]?.[key] ?? DICT.uz[key] ?? key;
    if (vars) for (const k of Object.keys(vars)) s = s.replaceAll(`{${k}}`, String(vars[k] ?? ""));
    return s;
  };
}

// Xato kodini foydalanuvchi tushunadigan matnga aylantirish
export function errText(t, e) {
  const code = e?.code || e?.message || "SERVER_ERROR";
  const s = t(`err_${code}`);
  return s.startsWith("err_") ? t("err_SERVER_ERROR") : s;
}
